def eq_speed(alpha):
    """Скорость установившегося планирования при данном угле атаки, м/с."""
    cl, cd = cl_of(alpha), cd_of(alpha)
    gamma = math.atan2(cd, max(cl, 0.05))
    return math.sqrt(2 * WEIGHT * math.cos(gamma) / (RHO * S_WING * max(cl, 0.05)))


def flight_reset(start_h=None):
    if start_h is not None:
        FL["start_h"] = float(start_h)
    FL["x"], FL["h"], FL["t"] = 0.0, FL["start_h"], 0.0
    FL["v"] = eq_speed(FL["alpha"])
    FL["running"], FL["landed"], FL["stalled"] = False, False, False
    FL["trail"] = []
    FL["trail_t"] = 0.0
    FL["gamma"] = math.atan2(cd_of(FL["alpha"]), cl_of(FL["alpha"]))
    FL["sink"], FL["gs"] = 0.0, FL["v"]
    FW["btn_run"].configure(text="▶  Старт")


def flight_step(dt):
    """Один маленький шаг моделирования (dt — секунды)."""
    a = FL["alpha"]
    cl, cd = cl_of(a), cd_of(a)
    stalled = a > ALPHA_STALL
    if stalled:                                   # срыв: медленно и крутое проваливание
        v_target = 0.8 * stall_speed()
        gamma = math.atan2(5.0, v_target)
    else:
        gamma = math.atan2(cd, max(cl, 0.05))     # угол планирования: tg θ = Сх / Су
        v_target = math.sqrt(2 * WEIGHT * math.cos(gamma) / (RHO * S_WING * max(cl, 0.05)))
    FL["v"] += (v_target - FL["v"]) * min(1.0, dt / 1.2)    # скорость плавно «подтягивается»
    v = FL["v"]
    sink = v * math.sin(gamma) - FL["thermal"]              # потеря высоты (минус поток)
    ground = v * math.cos(gamma) - FL["wind"]               # скорость относительно земли
    FL["x"] += ground * dt
    FL["h"] -= sink * dt
    FL["h"] = min(FL["h"], FL["start_h"] * 1.3)             # «потолок» облаков
    FL["t"] += dt
    FL["gamma"], FL["sink"], FL["gs"] = gamma, sink, ground
    FL["cl"], FL["cd"], FL["stalled"] = cl, cd, stalled
    FL["trail_t"] += dt
    if FL["trail_t"] > 0.4 * FL["scale"] ** 0.5:
        FL["trail_t"] = 0.0
        FL["trail"].append((FL["x"], FL["h"]))
        if len(FL["trail"]) > 300:
            FL["trail"].pop(0)
    if FL["h"] <= 0:
        FL["h"] = 0.0
        FL["landed"] = True
        FL["running"] = False
        FW["btn_run"].configure(text="▶  Старт")


def flight_tick(dt):
    if FL["running"] and not FL["landed"]:
        sim = dt * FL["scale"]
        n = max(1, int(sim / 0.05))
        for _ in range(n):
            if FL["landed"]:
                break
            flight_step(sim / n)
    draw_flight()
    update_flight_readouts()


