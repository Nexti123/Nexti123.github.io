def hex_to_rgb(h):
    """'#ff8800' -> [255, 136, 0]"""
    h = h.lstrip("#")
    return [int(h[i:i + 2], 16) for i in (0, 2, 4)]


def rgb_to_hex(rgb):
    """[255, 136, 0] -> '#ff8800' (числа обрезаются до 0..255)"""
    return "#%02x%02x%02x" % tuple(max(0, min(255, int(round(v)))) for v in rgb)


def mix(c1, c2, t):
    """Смешивает два цвета: t=0 -> c1, t=1 -> c2 (так делаем «прозрачность»)."""
    a, b = hex_to_rgb(c1), hex_to_rgb(c2)
    return rgb_to_hex([a[i] + (b[i] - a[i]) * t for i in range(3)])


def shade(color, k):
    """Делает цвет темнее (k < 1) или светлее (k > 1)."""
    return rgb_to_hex([v * k for v in hex_to_rgb(color)])


