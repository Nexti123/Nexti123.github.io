def draw_airfoil_view(cv, x0, y0, x1, y1):
    """Профиль крыла в потоке: линии потока, силы Y, X и вес G."""
    cv.create_rectangle(x0, y0, x1, y1, fill=CARD, outline=LINE)
    cv.create_text(x0 + 12, y0 + 9, anchor="nw", text="Профиль крыла в потоке воздуха",
                   fill=TEXT, font=(FONT, 10, "bold"))
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2 + 8
    a = AERO["alpha"]
    v = AERO["v"] / 3.6
    chord_px = min(300, (x1 - x0) * 0.42)

    # линии потока (пунктир «бежит» слева направо, скорость зависит от V)
    off = int(AERO["anim"] * (v / 15.0) * 60) % 24
    for k in range(-5, 6):
        yy = cy + k * 30
        if y0 + 34 < yy < y1 - 10:
            cv.create_line(x0 + 10, yy, x1 - 10, yy, fill="#2B3F73", width=2,
                           dash=(12, 12), dashoffset=-off)

    # профиль (повёрнут на угол атаки: носок выше)
    pts = []
    ca = math.cos(math.radians(a))
    sa = math.sin(math.radians(a))
    upper, lower = [], []
    for i in range(0, 21):
        x = i / 20
        yt = naca_half_thickness(x, 0.12)
        yc = 0.04 * (2 * 0.4 * x - x * x) / 0.16 if x < 0.4 else \
            0.04 * ((1 - 2 * 0.4) + 2 * 0.4 * x - x * x) / 0.36
        upper.append((x, yc + yt))
        lower.append((x, yc - yt))
    for x, y in upper + lower[::-1]:
        lx, ly = (x - 0.5) * chord_px, y * chord_px
        rx = lx * ca + ly * sa                    # поворот на угол атаки
        ry = -lx * sa + ly * ca
        pts.append(cx + rx)
        pts.append(cy - ry)
    stalled = a > ALPHA_STALL
    cv.create_polygon(pts, fill="#EFE6D2", outline="#FFFFFF", width=1)
    if stalled:                                   # завихрения за крылом при срыве
        for k in range(5):
            wob = math.sin(AERO["anim"] * 8 + k) * 6
            cv.create_line(cx - chord_px * 0.1 + k * 18, cy - 20 - k * 5 + wob,
                           cx + chord_px * 0.5 + k * 22, cy - 10 - k * 7 - wob,
                           fill=RED, dash=(3, 4), smooth=True)
        cv.create_text(cx, y0 + 40, text="СРЫВ ПОТОКА: подъёмная сила падает",
                       fill=RED, font=(FONT, 11, "bold"))

    # стрелки сил (масштаб: вес G = 100 пикселей)
    scale = 100.0 / WEIGHT
    ly_ = lift_force(v, a) * scale
    dx_ = drag_force(v, a) * scale
    px, py = cx - chord_px * 0.25 * ca, cy
    draw_arrow(cv, px, py, px, py - min(ly_, 170), GREEN, f"Y = {lift_force(v, a):.0f} Н")
    draw_arrow(cv, px + 40, py + 10, px + 40 + max(dx_, 6), py + 10, ORANGE,
               f"X = {drag_force(v, a):.0f} Н", 3)
    gx = cx + chord_px * 0.45
    draw_arrow(cv, gx, py, gx, py + 100, ACCENT, f"G = {WEIGHT:.0f} Н")
    cv.create_text(x0 + 12, y1 - 12, anchor="sw", fill=MUTED, font=(FONT, 9),
                   text="Длина стрелок — в одном масштабе. Вес G — 100 px. Когда Y ≥ G, крыло держит планер.")


