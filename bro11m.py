# Система координат модели (в метрах):
#   X — вправо (от пилота), Y — вверх, Z — вперёд (нос планера).
# Планер состоит из ГРАНЕЙ. Грань — это многоугольник (список точек x,y,z).
FACES = []                                   # все грани планера
CTRL = {}                                    # «как двигается» каждая подвижная деталь
CTL = {"elev": 0.0, "ail": 0.0, "rud": 0.0}  # положение рулей, градусы
#   elev > 0: ручка на себя (РВ вверх);  ail > 0: ручка влево;  rud > 0: левая педаль

C_WING = "#EFE6D2"
