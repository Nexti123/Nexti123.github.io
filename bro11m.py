ST = {"t": 0.0, "wins": [], "w": 0, "h": 0}
ST_STARS = [(random.random(), random.random() * 0.75, random.choice([1, 1, 2]),
             random.uniform(0.3, 1.0)) for _ in range(170)]
ST_CLOUDS = [(random.random(), random.uniform(0.08, 0.6), random.uniform(0.7, 1.5),
              random.uniform(4, 12)) for _ in range(7)]


def start_layout():
    """Перерисовывает неподвижную часть: небо, звёзды, холмы, заголовок, кнопки."""
    cv = ST["cv"]
    w, h = max(cv.winfo_width(), 600), max(cv.winfo_height(), 500)
    ST["w"], ST["h"] = w, h
    cv.delete("bg")
    cv.delete("title")
    horizon = h * 0.80
    bands = 36
    for i in range(bands):
        t = i / (bands - 1)
        col = mix("#050814", "#2E4A94", t ** 1.6)
        cv.create_rectangle(0, horizon * i / bands, w, horizon * (i + 1) / bands + 1,
                            fill=col, outline="", tags="bg")
    for nx, ny, size, br in ST_STARS:
        cv.create_rectangle(nx * w, ny * horizon, nx * w + size, ny * horizon + size,
                            fill=mix("#AFC8FF", "#050814", 1 - br), outline="", tags="bg")
    # дальние и ближние холмы
    for base, col, amp, ph in ((horizon - 14, "#0C1430", 40, 0.5), (horizon + 6, "#070B18", 55, 2.0)):
        pts = [0, h]
        for i in range(0, 41):
            x = w * i / 40
            y = base - amp * (0.5 + 0.5 * math.sin(i * 0.45 + ph)) * (0.6 + 0.4 * math.sin(i * 0.17 + ph))
            pts += [x, y]
        pts += [w, h]
        cv.create_polygon(pts, fill=col, outline="", tags="bg")

    cx = w / 2
    ty = h * 0.20
    for dx, dy, col in ((3, 3, "#0A1636"), (0, 0, TEXT)):
        cv.create_text(cx + dx, ty + dy, text="БРО-11М", fill=col, font=(FONT, 64, "bold"), tags="title")
