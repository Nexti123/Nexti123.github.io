def v_add(a, b):
    return (a[0] + b[0], a[1] + b[1], a[2] + b[2])


def v_sub(a, b):
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def v_mul(a, k):
    return (a[0] * k, a[1] * k, a[2] * k)


def v_dot(a, b):
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def v_cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def v_unit(a):
    length = math.sqrt(v_dot(a, a)) or 1.0
    return (a[0] / length, a[1] / length, a[2] / length)


def lerp3(a, b, t):
    """Точка на отрезке a-b (t от 0 до 1)."""
    return (a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t)


def rotate_about(p, pivot, axis, ang):
    """Поворачивает точку p вокруг оси (через точку pivot) на угол ang (радианы)."""
    v = v_sub(p, pivot)
    c, s = math.cos(ang), math.sin(ang)
    kxv = v_cross(axis, v)
    kdv = v_dot(axis, v)
    r = (v[0] * c + kxv[0] * s + axis[0] * kdv * (1 - c),
         v[1] * c + kxv[1] * s + axis[1] * kdv * (1 - c),
         v[2] * c + kxv[2] * s + axis[2] * kdv * (1 - c))
    return v_add(pivot, r)


def apply_ctrl(p, specs):
    """Сдвигает/поворачивает точку так, как это делает подвижная деталь."""
    for kind, a, b, key, factor in specs:
        val = CTL[key] * factor
        if val == 0:
            continue
        if kind == "move":                       # a — направление сдвига
            p = (p[0] + a[0] * val, p[1] + a[1] * val, p[2] + a[2] * val)
        else:                                    # "rot": a — центр, b — ось, val — градусы
            p = rotate_about(p, a, b, math.radians(val))
    return p


def add_face(pts, group, color, ctrl=None):
    FACES.append({"pts": pts, "group": group, "color": color, "ctrl": ctrl})


# индексы углов для параллелепипеда: 0-3 — передний «квадрат», 4-7 — задний
BOX_FACES = [(0, 1, 2, 3), (4, 5, 6, 7), (0, 1, 5, 4), (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)]


def add_hexahedron(corners, group, color, ctrl=None):
    for idx in BOX_FACES:
        add_face([corners[i] for i in idx], group, color, ctrl)


def add_box(center, size, group, color, ctrl=None):
    """Коробка: центр (x,y,z) и размеры (ширина, высота, длина)."""
    x, y, z = center
    sx, sy, sz = size[0] / 2, size[1] / 2, size[2] / 2
    loop = [(-sx, -sy), (sx, -sy), (sx, sy), (-sx, sy)]
    corners = [(x + dx, y + dy, z + sz) for dx, dy in loop] + \
              [(x + dx, y + dy, z - sz) for dx, dy in loop]
    add_hexahedron(corners, group, color, ctrl)


def add_frustum(z0, w0, h0, z1, w1, h1, cy, group, color):
    """Усечённая пирамида вдоль оси Z (для носового обтекателя)."""
    l0 = [(-w0 / 2, -h0 / 2), (w0 / 2, -h0 / 2), (w0 / 2, h0 / 2), (-w0 / 2, h0 / 2)]
    l1 = [(-w1 / 2, -h1 / 2), (w1 / 2, -h1 / 2), (w1 / 2, h1 / 2), (-w1 / 2, h1 / 2)]
    corners = [(dx, cy + dy, z0) for dx, dy in l0] + [(dx, cy + dy, z1) for dx, dy in l1]
    add_hexahedron(corners, group, color)


def add_beam(p1, p2, r, group, color, ctrl=None):
    """Тонкий стержень (труба/трос) между двумя точками, r — «радиус»."""
    d = v_unit(v_sub(p2, p1))
    helper = (0, 1, 0) if abs(d[1]) < 0.9 else (1, 0, 0)
    u = v_unit(v_cross(d, helper))
    w = v_cross(d, u)
    offs = [v_add(v_mul(u, -r), v_mul(w, -r)), v_add(v_mul(u, r), v_mul(w, -r)),
            v_add(v_mul(u, r), v_mul(w, r)), v_add(v_mul(u, -r), v_mul(w, r))]
    corners = [v_add(p1, o) for o in offs] + [v_add(p2, o) for o in offs]
    add_hexahedron(corners, group, color, ctrl)


def add_wheel(cx, cy, cz, r, width, group, color, n=12):
    """Колесо: ось вдоль X."""
    left, right = [], []
    for i in range(n):
        a = 2 * math.pi * i / n
        y, z = cy + r * math.cos(a), cz + r * math.sin(a)
        left.append((cx - width / 2, y, z))
        right.append((cx + width / 2, y, z))
    add_face(left, group, color)
    add_face(right, group, color)
    for i in range(n):
        j = (i + 1) % n
        add_face([left[i], left[j], right[j], right[i]], group, color)


def naca_half_thickness(x, t=0.12):
    """Половина толщины профиля (доля хорды) на расстоянии x от носка (формула NACA)."""
    return 5 * t * (0.2969 * math.sqrt(x) - 0.1260 * x - 0.3516 * x * x
                    + 0.2843 * x ** 3 - 0.1015 * x ** 4)


def add_panel(le0, te0, le1, te1, nvec, a, b, group, color, ctrl=None, thick=0.12, m=6):
    """
    Поверхность с профилем (крыло, стабилизатор, киль, руль...).
    le0/te0 — передняя/задняя кромка у корня, le1/te1 — на конце.
    nvec — направление «толщины», a..b — какую часть хорды строим (0 — носок, 1 — кромка).
    """
    xs = [a + (b - a) * i / m for i in range(m + 1)]
    loops = []
    for le, te in ((le0, te0), (le1, te1)):
        chord = v_sub(te, le)
        c_len = math.sqrt(v_dot(chord, chord))
        upper, lower = [], []
        for x in xs:
            base = v_add(le, v_mul(chord, x))
            t = naca_half_thickness(x, thick) * c_len
            upper.append(v_add(base, v_mul(nvec, t)))
            lower.append(v_sub(base, v_mul(nvec, t)))
        loops.append(upper + lower[::-1])
    l0, l1 = loops
    n = len(l0)
    for i in range(n):
        j = (i + 1) % n
        add_face([l0[i], l0[j], l1[j], l1[i]], group, color, ctrl)
    add_face(l0, group, color, ctrl)
    add_face(l1, group, color, ctrl)


def point_on(le, te, x):
    return v_add(le, v_mul(v_sub(te, le), x))


def hinge_axis(p0, p1):
    """Единичный вектор вдоль оси навески (всегда «в сторону +X» или «вверх»)."""
    ax = v_unit(v_sub(p1, p0))
    if ax[0] < -1e-9 or (abs(ax[0]) <= 1e-9 and ax[1] < 0):
        ax = v_mul(ax, -1)
    return ax


def build_wing_half(side):
    """Одна консоль крыла: side = -1 (левая) или +1 (правая)."""
    half = SPAN / 2
    dih = math.tan(math.radians(4.0))             # поперечное V крыла ≈ 4°
    yw = 1.95                                     # высота крыла над землёй
    le0, te0 = (0, yw, 0.5), (0, yw, 0.5 - CHORD)
    le1 = (side * half, yw + half * dih, 0.5)
    te1 = (side * half, yw + half * dih, 0.5 - CHORD)
    up = (0, 1, 0)
    add_panel(le0, te0, le1, te1, up, 0.0, 0.75, "wing", C_WING)           # передняя часть
    s_a = 0.55                                    # элерон занимает внешние 45% полукрыла
    la, ta = lerp3(le0, le1, s_a), lerp3(te0, te1, s_a)
    add_panel(le0, te0, la, ta, up, 0.75, 1.0, "wing", C_WING)             # задняя часть у корня
    name = "ail_L" if side < 0 else "ail_R"
    add_panel(la, ta, le1, te1, up, 0.75, 1.0, "aileron", C_AIL, name)     # элерон
    h0, h1 = point_on(la, ta, 0.75), point_on(le1, te1, 0.75)
    axis = hinge_axis(h0, h1)
    CTRL[name] = [("rot", h0, axis, "ail", +1 if side < 0 else -1)]


