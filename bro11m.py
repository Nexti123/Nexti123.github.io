QZ = {"i": 0, "score": 0, "answered": False, "order": [], "finished": False}
QW = {}


def quiz_show_question():
    q = QUIZ[QZ["i"]]
    options = list(enumerate(q[1]))
    random.shuffle(options)                       # перемешиваем варианты ответов
    QZ["order"] = options
    QZ["answered"] = False
    QW["progress"].configure(text=f"Вопрос {QZ['i'] + 1} из {len(QUIZ)}    ·    верно: {QZ['score']}")
    QW["question"].configure(text=q[0])
    QW["feedback"].configure(text="")
    for k, b in enumerate(QW["opts"]):
        b.configure(text=f"{k + 1}.  {options[k][1]}")
        recolor(b, "#1B2340", "#2A3560")
        b.pack(fill="x", pady=5)
    QW["next"].configure(text="")
    QW["next"].pack_forget()


def quiz_answer(k):
    if QZ["answered"] or QZ["finished"]:
        return
    QZ["answered"] = True
    q = QUIZ[QZ["i"]]
    chosen = QZ["order"][k][0]
    right_pos = [pos for pos, (orig, _t) in enumerate(QZ["order"]) if orig == q[2]][0]
    recolor(QW["opts"][right_pos], "#1F7A48", "#1F7A48")
    if chosen == q[2]:
        QZ["score"] += 1
        QW["feedback"].configure(text="Верно!  " + q[3], fg=GREEN)
    else:
        recolor(QW["opts"][k], "#8A2A38", "#8A2A38")
        QW["feedback"].configure(text="Неверно.  " + q[3], fg=RED)
    last = QZ["i"] == len(QUIZ) - 1
    QW["next"].configure(text="Результат  →" if last else "Дальше  →")
    QW["next"].pack(anchor="e", pady=(14, 0))
    QW["progress"].configure(text=f"Вопрос {QZ['i'] + 1} из {len(QUIZ)}    ·    верно: {QZ['score']}")


def quiz_next():
    if QZ["i"] >= len(QUIZ) - 1:
        quiz_finish()
        return
    QZ["i"] += 1
    quiz_show_question()


def quiz_finish():
    QZ["finished"] = True
    for b in QW["opts"]:
        b.pack_forget()
    QW["next"].pack_forget()
    pct = QZ["score"] / len(QUIZ)
    if pct >= 0.9:
        verdict = "Отлично! Ты хорошо знаешь конспект."
    elif pct >= 0.6:
        verdict = "Хорошо. Повтори вкладки «Модель» и «Законы» и попробуй ещё раз."
    else:
        verdict = "Стоит повторить конспект и покрутить 3D-модель, потом пройти тест заново."
    QW["progress"].configure(text="Тест завершён")
    QW["question"].configure(text=f"Твой результат: {QZ['score']} из {len(QUIZ)}")
    QW["feedback"].configure(text=verdict, fg=TEXT)
    QW["next"].configure(text="Пройти заново")
    QW["next"].pack(anchor="e", pady=(14, 0))


def quiz_restart():
    QZ["i"], QZ["score"], QZ["finished"] = 0, 0, False
    quiz_show_question()


def quiz_next_click():
    if QZ["finished"]:
        quiz_restart()
    else:
        quiz_next()


