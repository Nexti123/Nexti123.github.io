# Размеры взяты для БРО-11МС (учебный планер ЮПШ, данные СибНИА).
SPAN = 7.82          # размах крыла, м
CHORD = 1.45         # средняя хорда крыла, м
S_WING = 10.9        # площадь крыла, м²
LENGTH = 5.47        # длина планера, м
K_MAX = 12           # максимальное качество (по данным)
MASS = 100.0         # масса планера с пилотом, кг (УЧЕБНОЕ ДОПУЩЕНИЕ)
G = 9.81             # ускорение свободного падения, м/с²
RHO = 1.225          # плотность воздуха у земли, кг/м³
WEIGHT = MASS * G    # вес, Н

# --- учебная модель крыла (подобрана так, чтобы K_макс ≈ 12) ---
AR = SPAN ** 2 / S_WING                       # удлинение крыла λ = l² / S
E_OSW = 0.8                                   # коэффициент формы (индуктивное сопротивление)
CD0 = 0.0245                                  # сопротивление при нулевой подъёмной силе
ALPHA0 = -3.0                                 # угол нулевой подъёмной силы, °
ALPHA_STALL = 14.0                            # критический угол атаки, °
A_SLOPE = 2 * math.pi / (1 + 2 / AR)          # наклон кривой Су(α), 1/рад


def cl_of(alpha):
    """Коэффициент подъёмной силы Су при угле атаки alpha (в градусах)."""
    if alpha <= ALPHA_STALL:
        return A_SLOPE * math.radians(alpha - ALPHA0)
    cl_max = A_SLOPE * math.radians(ALPHA_STALL - ALPHA0)
    return max(0.55, cl_max - 0.045 * (alpha - ALPHA_STALL))   # после срыва Су падает


def cd_of(alpha):
    """Коэффициент лобового сопротивления Сх: Сх = Сх0 + Су² / (π·λ·e)."""
    cl = cl_of(alpha)
    cd = CD0 + cl * cl / (math.pi * E_OSW * AR)
    if alpha > ALPHA_STALL:
        cd += 0.025 * (alpha - ALPHA_STALL)                    # срыв резко увеличивает сопротивление
    return cd


def lift_force(v_ms, alpha):
    """Подъёмная сила Y = Су·ρ·V²·S/2, Н."""
    return cl_of(alpha) * RHO * v_ms ** 2 * S_WING / 2


def drag_force(v_ms, alpha):
    """Лобовое сопротивление X = Сх·ρ·V²·S/2, Н."""
    return cd_of(alpha) * RHO * v_ms ** 2 * S_WING / 2


def stall_speed():
    """Скорость срыва (при максимальном Су), м/с."""
    return math.sqrt(2 * WEIGHT / (RHO * S_WING * cl_of(ALPHA_STALL)))


def kmh(v_ms):
    return v_ms * 3.6


