def main_tick():
    """Главный цикл: раз в ~33 мс вызывает tick() активного экрана."""
    now = time.perf_counter()
    dt = min(now - APP["last"], 0.1)
    APP["last"] = now
    scr = SCREENS.get(APP["current"])
    if scr and scr.get("tick"):
        scr["tick"](dt)
    APP["root"].after(33, main_tick)


