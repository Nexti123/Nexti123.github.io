def render_model():
    """Рисует все грани: поворот -> перспектива -> сортировка (дальние сначала)."""
    cv = M["cv"]
    w = max(cv.winfo_width(), 200)
    h = max(cv.winfo_height(), 200)
    cv.delete("all")
    yaw, pitch = math.radians(M["yaw"]), math.radians(M["pitch"])
    cyw, syw = math.cos(yaw), math.sin(yaw)
    cp, sp = math.cos(pitch), math.sin(pitch)
    dist = 10.0                                   # расстояние до камеры, м
    focal = min(w, h) * 1.15 * M["zoom"]          # «фокусное расстояние» в пикселях
    mx, my = w / 2, h / 2

    def to_cam(p):
        """Мировые координаты -> координаты камеры (после поворота модели)."""
        x, y, z = p[0] - CENTER[0], p[1] - CENTER[1], p[2] - CENTER[2]
        x1 = x * cyw + z * syw                    # поворот вокруг вертикальной оси
        z1 = -x * syw + z * cyw
        y2 = y * cp - z1 * sp                     # наклон вверх/вниз
        z2 = y * sp + z1 * cp
        return (x1, y2, z2 + dist)

    def to_screen(q):
        k = focal / q[2]                          # перспектива: дальше -> меньше
        return (mx + q[0] * k, my - q[1] * k)

    # сетка «земли»
    gcol = "#1A2238"
    lines = []
    for i in range(-5, 6):
        lines.append(((i, 0, -6), (i, 0, 4)))
    for j in range(-6, 5):
        lines.append(((-5, 0, j), (5, 0, j)))
    for a, b in lines:
        qa, qb = to_cam(a), to_cam(b)
        if qa[2] > 0.5 and qb[2] > 0.5:
            xa, ya = to_screen(qa)
            xb, yb = to_screen(qb)
            cv.create_line(xa, ya, xb, yb, fill=gcol)

    # преобразуем грани
    items = []
    for f in FACES:
        specs = CTRL.get(f["ctrl"]) if f["ctrl"] else None
        qs = []
        ok = True
        for p in f["pts"]:
            if specs:
                p = apply_ctrl(p, specs)
            q = to_cam(p)
            if q[2] < 0.5:
                ok = False
                break
            qs.append(q)
        if not ok:
            continue
        depth = sum(q[2] for q in qs) / len(qs)
        nr = v_cross(v_sub(qs[1], qs[0]), v_sub(qs[2], qs[0]))
        ln = math.sqrt(v_dot(nr, nr))
        if ln > 1e-9:
            light = 0.30 + 0.70 * abs(v_dot((nr[0] / ln, nr[1] / ln, nr[2] / ln), LIGHT))
        else:
            light = 0.6
        items.append((depth, f, qs, light))
    items.sort(key=lambda it: -it[0])             # сначала самые дальние

    hits = []
    sel, hov = M["sel"], M["hover"]
    for depth, f, qs, light in items:
        pts = []
        for q in qs:
            sx, sy = to_screen(q)
            pts.append(sx)
            pts.append(sy)
        g = f["group"]
        col = shade(f["color"], light)
        if g == sel:
            col = mix(col, YELLOW, 0.55)
            outline = "#FFFFFF"
        elif g == hov:
            col = mix(col, "#FFFFFF", 0.30)
            outline = "#FFFFFF"
        else:
            outline = mix(col, "#0B0F19", 0.6)
        if M["wire"]:
            line_col = YELLOW if g == sel else ("#FFFFFF" if g == hov else f["color"])
            cv.create_polygon(pts, fill="", outline=line_col)
        else:
            cv.create_polygon(pts, fill=col, outline=outline)
        hits.append((pts, g))
    M["hits"] = hits

