def nudge(slider, delta, lo, hi):
    slider_put(slider, max(lo, min(hi, slider_get(slider) + delta)))


def on_key(event):
    key = event.keysym
    scr = APP["current"]
    if scr == "model":
        if key == "Up":
            nudge(MW["s_elev"], -2, -20, 20)       # ручка от себя
        elif key == "Down":
            nudge(MW["s_elev"], +2, -20, 20)       # ручка на себя
        elif key == "Left":
            nudge(MW["s_ail"], -2, -20, 20)        # ручка влево
        elif key == "Right":
            nudge(MW["s_ail"], +2, -20, 20)
        elif key in ("z", "Z"):
            nudge(MW["s_rud"], -3, -25, 25)        # левая педаль
        elif key in ("x", "X"):
            nudge(MW["s_rud"], +3, -25, 25)
        elif key in ("c", "C"):
            center_controls()
    elif scr == "flight":
        if key == "Up":
            nudge(FW["s_alpha"], -0.5, 0, 16)      # ручка от себя: угол атаки меньше
        elif key == "Down":
            nudge(FW["s_alpha"], +0.5, 0, 16)
        elif key == "space":
            toggle_run()


