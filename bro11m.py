def hover_button(parent, text, command, base="#1B2340", hover="#2A3560",
                 fg=TEXT, size=10, pady=8, padx=12):
    """Кнопка, которая плавно меняет цвет при наведении."""
    btn = tk.Label(parent, text=text, bg=base, fg=fg, font=(FONT, size, "bold"),
                   pady=pady, padx=padx, cursor="hand2")
    st = {"base": base, "hover": hover, "cur": hex_to_rgb(base),
          "target": hex_to_rgb(base), "busy": False, "inside": False}

    def step():
        done = True
        for i in range(3):
            diff = st["target"][i] - st["cur"][i]
            if abs(diff) > 1:
                st["cur"][i] += diff * 0.35
                done = False
            else:
                st["cur"][i] = st["target"][i]
        btn.configure(bg=rgb_to_hex(st["cur"]))
        if done:
            st["busy"] = False
        else:
            btn.after(16, step)

    def go(color):
        st["target"] = hex_to_rgb(color)
        if not st["busy"]:
            st["busy"] = True
            step()

    def on_enter(_event):
        st["inside"] = True
        go(st["hover"])

    def on_leave(_event):
        st["inside"] = False
        go(st["base"])

    btn.bind("<Enter>", on_enter)
    btn.bind("<Leave>", on_leave)
    btn.bind("<Button-1>", lambda e: command())
    st["go"] = go
    btn.st = st
    return btn


def recolor(btn, base, hover):
    """Меняет «обычный» и «наведённый» цвет кнопки."""
    st = btn.st
    st["base"], st["hover"] = base, hover
    st["go"](hover if st["inside"] else base)


def set_toggle(btn, active):
    """Подсвечивает кнопку-переключатель синим, если она включена."""
    if active:
        recolor(btn, "#2A4FB8", "#4670E6")
    else:
        recolor(btn, "#1B2340", "#2A3560")


def make_slider(parent, vmin, vmax, value, command, bg=PANEL, center_mark=False):
    """Свой ползунок на Canvas. Возвращает Canvas; значение: slider_get / slider_put."""
    cv = tk.Canvas(parent, height=30, bg=bg, highlightthickness=0, cursor="hand2")
    st = {"v": float(value), "hover": False, "drag": False}
    pad = 12

    def redraw():
        cv.delete("all")
        w = max(cv.winfo_width(), 60)
        y = 15
        x = pad + (w - 2 * pad) * (st["v"] - vmin) / (vmax - vmin)
        cv.create_line(pad, y, w - pad, y, fill="#222B45", width=5, capstyle="round")
        if center_mark:
            xm = pad + (w - 2 * pad) * 0.5
            cv.create_line(xm, y - 8, xm, y + 8, fill="#3A4670", width=2)
            cv.create_line(xm, y, x, y, fill=ACCENT, width=5, capstyle="round")
        else:
            cv.create_line(pad, y, x, y, fill=ACCENT, width=5, capstyle="round")
        if st["hover"] or st["drag"]:
            cv.create_oval(x - 13, y - 13, x + 13, y + 13,
                           fill=mix(ACCENT, bg, 0.7), outline="")
        cv.create_oval(x - 8, y - 8, x + 8, y + 8, fill="#EAF0FF", outline=ACCENT, width=2)

    def set_from_x(px):
        w = max(cv.winfo_width(), 60)
        frac = (px - pad) / (w - 2 * pad)
        st["v"] = vmin + max(0.0, min(1.0, frac)) * (vmax - vmin)
        redraw()
        command(st["v"])

    def on_press(e):
        st["drag"] = True
        set_from_x(e.x)

    def on_move(e):
        set_from_x(e.x)

    def on_release(_e):
        st["drag"] = False
        redraw()

    def on_enter(_e):
        st["hover"] = True
        redraw()

    def on_leave(_e):
        st["hover"] = False
        redraw()

    def on_double(_e):
        slider_put(cv, (vmin + vmax) / 2)

    cv.bind("<Configure>", lambda e: redraw())
    cv.bind("<Button-1>", on_press)
    cv.bind("<B1-Motion>", on_move)
    cv.bind("<ButtonRelease-1>", on_release)
    cv.bind("<Enter>", on_enter)
    cv.bind("<Leave>", on_leave)
    cv.bind("<Double-Button-1>", on_double)
    cv.slider_state = st
    cv.slider_redraw = redraw
    cv.slider_command = command
    return cv


def slider_get(slider):
    return slider.slider_state["v"]


def slider_put(slider, value, call=True):
    """Программно ставит ползунок в нужное значение."""
    slider.slider_state["v"] = float(value)
    slider.slider_redraw()
    if call:
        slider.slider_command(float(value))


