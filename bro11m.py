def point_in_poly(x, y, pts):
    """Лежит ли точка (x, y) внутри многоугольника (метод луча)."""
    inside = False
    n = len(pts) // 2
    j = n - 1
    for i in range(n):
        xi, yi = pts[2 * i], pts[2 * i + 1]
        xj, yj = pts[2 * j], pts[2 * j + 1]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi + 1e-12) + xi:
            inside = not inside
        j = i
    return inside


def pick_group(x, y):
    """Какая деталь под курсором? Идём от ближних граней к дальним."""
    for pts, g in reversed(M["hits"]):
        if point_in_poly(x, y, pts):
            return g
    return None


