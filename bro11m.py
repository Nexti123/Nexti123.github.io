def draw_glider_side(cv, px, py, scale, theta_deg, tag):
    """Рисует силуэт. (px, py) — положение центра тяжести на экране."""
    th = math.radians(theta_deg)
    c, s = math.cos(th), math.sin(th)
    cgx, cgy = 0.0, 1.0

    def tr(p):
        dx, dy = (p[0] - cgx) * scale, (p[1] - cgy) * scale
        return (px + dx * c - dy * s, py - (dx * s + dy * c))

    for item in sprite_polys():
        kind, pts, col = item[0], item[1], item[2]
        if kind == "poly":
            flat = []
            for p in pts:
                x, y = tr(p)
                flat.append(x)
                flat.append(y)
            cv.create_polygon(flat, fill=col, outline=mix(col, "#000000", 0.45), tags=tag)
        elif kind == "line":
            x0, y0 = tr(pts[0])
            x1, y1 = tr(pts[1])
            cv.create_line(x0, y0, x1, y1, fill=col, width=max(1, scale * 0.05), tags=tag)
        else:
            x, y = tr(pts[0])
            r = item[3] * scale
            cv.create_oval(x - r, y - r, x + r, y + r, fill=col,
                           outline=mix(col, "#000000", 0.45), tags=tag)


def draw_flight():
    cv = FW["cv"]
    w = max(cv.winfo_width(), 400)
    h = max(cv.winfo_height(), 300)
    cv.delete("all")
    ground_y = h - 80
    top = max(FL["start_h"] * 1.3, 5.0)
    kv = min(40.0, (ground_y - 110) / top)        # пикселей на метр высоты
    kx = 5.0                                      # пикселей на метр дальности
    gx = w * 0.34                                 # где на экране планер по горизонтали

    # небо (полосы-градиент)
    bands = 28
    for i in range(bands):
        t = i / (bands - 1)
        col = mix("#0A1230", "#27407F", t ** 1.3)
        cv.create_rectangle(0, ground_y * i / bands, w, ground_y * (i + 1) / bands + 1,
                            fill=col, outline="")
    # облака (медленнее, чем земля — «параллакс»)
    for cx0, cy0, sc in FW_CLOUDS:
        x = (cx0 * w * 1.6 - FL["x"] * kx * 0.12) % (w * 1.6) - w * 0.3
        y = 40 + cy0 * (ground_y * 0.35)
        for dx, dy, rr in ((0, 0, 26), (28, -8, 32), (58, 0, 24), (30, 8, 28)):
            cv.create_oval(x + dx * sc - rr * sc, y + dy * sc - rr * sc * 0.6,
                           x + dx * sc + rr * sc, y + dy * sc + rr * sc * 0.6,
                           fill="#2A3F7A", outline="")
    # земля
    cv.create_rectangle(0, ground_y, w, h, fill="#0E1626", outline="")
    cv.create_line(0, ground_y, w, ground_y, fill="#3A5A9A", width=2)
    first = int((FL["x"] - gx / kx) // 50) - 1
    last = int((FL["x"] + (w - gx) / kx) // 50) + 2
    for m in range(first, last):
        sx = gx + (m * 50 - FL["x"]) * kx
        cv.create_line(sx, ground_y, sx, ground_y + 10, fill="#3A5A9A")
        if m % 2 == 0:
            cv.create_text(sx, ground_y + 24, text=f"{m * 50} м", fill=MUTED, font=(FONT, 8))
    # шкала высоты
    step = 1
    for st in (1, 2, 5, 10, 20, 50, 100):
        step = st
        if top / st <= 7:
            break
    alt = 0
    while alt <= top:
        y = ground_y - alt * kv
        cv.create_line(40, y, 52, y, fill=MUTED)
        cv.create_text(36, y, anchor="e", text=f"{alt} м", fill=MUTED, font=(FONT, 8))
        alt += step
    cv.create_line(52, ground_y, 52, ground_y - top * kv, fill=LINE)

    # след
    for i, (tx, th_) in enumerate(FL["trail"]):
        sx = gx + (tx - FL["x"]) * kx
        sy = ground_y - th_ * kv
        if 0 < sx < w:
            cv.create_oval(sx - 2, sy - 2, sx + 2, sy + 2,
                           fill=mix("#5B8CFF", "#0A1230", 0.55), outline="")
    # тень
    shadow_w = 60 + FL["h"] * 0.3
    cv.create_oval(gx - shadow_w / 2, ground_y - 4, gx + shadow_w / 2, ground_y + 5,
                   fill="#050810", outline="")

    # планер
    scale = 26.0
    pitch = FL["alpha"] - math.degrees(FL["gamma"])          # наклон носа к горизонту
    if FL["stalled"]:
        pitch = 12.0
    cgy = ground_y - FL["h"] * kv - 1.0 * scale
    draw_glider_side(cv, gx, cgy, scale, pitch, "glider")

    # силы
