def draw_chart(cv, x0, y0, x1, y1, title, xs, ys, cur_x, cur_y, color, ymin, ymax, ticks):
    """Маленький график: кривая, сетка, красная линия срыва и маркер текущей точки."""
    cv.create_rectangle(x0, y0, x1, y1, fill=CARD, outline=LINE)
    cv.create_text(x0 + 12, y0 + 9, anchor="nw", text=title, fill=TEXT, font=(FONT, 10, "bold"))
    px0, py0, px1, py1 = x0 + 40, y0 + 36, x1 - 16, y1 - 28
    xmin, xmax = xs[0], xs[-1]

    def sx(x):
        return px0 + (px1 - px0) * (x - xmin) / (xmax - xmin)

    def sy(y):
        return py1 - (py1 - py0) * (y - ymin) / (ymax - ymin)

    for t in ticks:                               # горизонтальная сетка
        cv.create_line(px0, sy(t), px1, sy(t), fill=LINE)
        cv.create_text(px0 - 6, sy(t), anchor="e", text=f"{t:g}", fill=MUTED, font=(FONT, 8))
    for a in range(-4, 19, 4):                    # подписи оси α
        cv.create_text(sx(a), py1 + 12, text=f"{a}°", fill=MUTED, font=(FONT, 8))
    cv.create_line(sx(ALPHA_STALL), py0, sx(ALPHA_STALL), py1, fill=RED, dash=(4, 4))
    cv.create_text(sx(ALPHA_STALL) - 4, py0 + 2, anchor="ne", text="срыв", fill=RED,
                   font=(FONT, 8))
    flat = []
    for x, y in zip(xs, ys):
        flat.append(sx(x))
        flat.append(sy(max(ymin, min(ymax, y))))
    cv.create_line(*flat, fill=color, width=2)
    mx, my = sx(cur_x), sy(max(ymin, min(ymax, cur_y)))
    cv.create_line(mx, py1, mx, my, fill=mix(color, CARD, 0.5), dash=(3, 3))
    cv.create_oval(mx - 6, my - 6, mx + 6, my + 6, fill=mix(color, CARD, 0.6), outline="")
    cv.create_oval(mx - 4, my - 4, mx + 4, my + 4, fill="#FFFFFF", outline=color, width=2)


